"""Builds results/report.md from the per-implementation result files."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"
IMPLS = ["dotnet-system-formats-cbor", "python-cbor2", "rust-ciborium", "rust-dcbor"]
PROFILES = ["cde", "dcbor"]


def load(name: str) -> dict:
    return json.loads((RESULTS / f"{name}.json").read_text())


def short(s: str, n: int = 28) -> str:
    return s if len(s) <= n else s[: n - 1] + "…"


def main() -> None:
    fixtures = json.loads((ROOT / "fixtures/encode.json").read_text())["fixtures"]
    cases = json.loads((ROOT / "fixtures/decode.json").read_text())["cases"]
    ref = load("reference")["encode"]
    impls = [load(n) for n in IMPLS]
    modes = [(i, m) for i in impls for m in next(iter(i["encode"].values()))]
    lines = ["# CBOR determinism spike results", "",
             "Generated by `compare.py`; do not edit. Reference = `python/ref_encoder.py`, which reproduces every published",
             "vector in `fixtures/encode.json`.", "",
             "Versions: " + ", ".join(f"{i['impl']} {i['version']}" for i in impls), "",
             "## Encoding: agreement with the reference", "",
             f"{len(fixtures)} fixtures. A cell counts fixtures whose bytes equal the reference for that profile.", "",
             "| Implementation / mode | = CDE | = dCBOR | errors |", "|---|---:|---:|---:|"]
    for i, m in modes:
        got = {f["name"]: i["encode"][f["name"]][m] for f in fixtures}
        cells = [sum(got[n] == ref[n][p] for n in got) for p in PROFILES]
        lines.append(f"| {i['impl']} — {m} | {cells[0]} | {cells[1]} | {sum(v.startswith('error') for v in got.values())} |")

    lines += ["", "### Differences from CDE", "",
              "Fixtures where a mode differs from the CDE reference (dCBOR reference shown for comparison).", ""]
    for i, m in modes:
        diffs = [f["name"] for f in fixtures if i["encode"][f["name"]][m] != ref[f["name"]]["cde"]]
        if not diffs:
            lines += [f"**{i['impl']} — {m}:** none", ""]
            continue
        lines += [f"**{i['impl']} — {m}:** {len(diffs)}", "", "| Fixture | CDE | dCBOR | got |", "|---|---|---|---|"]
        lines += [f"| {n} | `{short(ref[n]['cde'])}` | `{short(ref[n]['dcbor'])}` | `{short(i['encode'][n][m], 44)}` |" for n in diffs]
        lines.append("")

    dec_modes = [(i, m) for i in impls for m in next(iter(i["decode"].values()))]
    lines += ["## Decoding: strictness", "",
              "`acc` = accepted, `rej` = rejected. Expected columns say whether a checking decoder for that profile must accept.", "",
              "| Case | hex | CDE | dCBOR | " + " | ".join(f"{i['impl'].split(' ', 1)[1]} {m}" for i, m in dec_modes) + " |",
              "|---|---|:-:|:-:|" + ":-:|" * len(dec_modes)]
    for c in cases:
        row = [("acc" if i["decode"][c["name"]][m] == "accept" else "rej") for i, m in dec_modes]
        exp = ["acc" if p in c["valid_in"] else "rej" for p in PROFILES]
        lines.append(f"| {c['name']} | `{short(c['hex'], 20)}` | {exp[0]} | {exp[1]} | " + " | ".join(row) + " |")
    lines += ["", "| Decoder | cases matching a CDE-checking decoder | cases matching a dCBOR-checking decoder |", "|---|---:|---:|"]
    for i, m in dec_modes:
        acc = {c["name"]: i["decode"][c["name"]][m] == "accept" for c in cases}
        score = [sum(acc[c["name"]] == (p in c["valid_in"]) for c in cases) for p in PROFILES]
        lines.append(f"| {i['impl']} {m} | {score[0]}/{len(cases)} | {score[1]}/{len(cases)} |")
    cddl = json.loads((ROOT / "fixtures/cddl.json").read_text())
    validators = [load("python-pycddl"), load("rust-cddl")]
    mark = lambda got, want: ("ok" if got.startswith("valid") == want else "**WRONG**") + (" (valid)" if got.startswith("valid") else " (invalid)")
    lines += ["", "## CDDL validation", "", "Versions: " + ", ".join(f"{v['impl']} {v['version']}" for v in validators), "",
              "| Instance | Schema | expected | " + " | ".join(v["impl"] for v in validators) + " |", "|---|---|---|" + "---|" * len(validators)]
    for i in cddl["instances"]:
        for schema in cddl["schemas"]:
            want = i["valid"][schema]
            lines.append(f"| {i['name']} | {schema} | {'valid' if want else 'invalid'} | " + " | ".join(mark(v["validate"][i["name"]][schema], want) for v in validators) + " |")
    lines += ["", "| Probe | schema | expected | " + " | ".join(v["impl"] for v in validators) + " |", "|---|---|---|" + "---|" * len(validators)]
    for p in cddl["probes"]:
        lines.append(f"| {p['name']} | `{p['schema'].replace(chr(10), '; ')}` | {'valid' if p['valid'] else 'invalid'} | " + " | ".join(mark(v["probes"][p["name"]], p["valid"]) for v in validators) + " |")
    (RESULTS / "report.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
